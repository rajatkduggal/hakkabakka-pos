CREATE TABLE IF NOT EXISTS pos_order_counters (
  year_month TEXT PRIMARY KEY,
  last_number INTEGER NOT NULL DEFAULT 0 CHECK(last_number >= 0)
);
CREATE INDEX IF NOT EXISTS idx_pos_tables_status ON pos_tables(status);
